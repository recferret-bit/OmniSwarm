import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { families } from './reviewer-families.mjs';
import { parseReviewerSpec } from './reviewer-registry.mjs';
import { dockerClientEnv } from './bridge-tools-common.mjs';
import { keyFingerprint } from './reviewer-env.mjs';
import { vendorOfOpenRouterModel as vendorOfOpenRouter } from './reviewer-registry.mjs';

test('a zai reviewer receives only its key and the bridge env receives neither key', () => {
  const work = fs.mkdtempSync(path.join(os.tmpdir(), 'api-launch-'));
  const env = { HOME: '/home/inert', PATH: '/bin', USER: 'inert', ZAI_API_KEY: 'zk-test', OPENROUTER_API_KEY: 'or-test', ZAI_BASE_URL: 'https://api.z.ai/api/paas/v4' };
  const launched = families.launch(parseReviewerSpec('key:zai:glm-5.3'), { workDir: work, bridgeArgs: ['--report-dir', work], env });
  assert.equal(launched.transport, 'api-acp');
  assert.equal(launched.invocation.env.ZAI_API_KEY, 'zk-test');
  assert.equal(launched.invocation.env.OPENROUTER_API_KEY, undefined);
  assert.equal(launched.bridgeEnv.ZAI_API_KEY, undefined);
  assert.equal(launched.bridgeEnv.OPENROUTER_API_KEY, undefined);
  const config = fs.readFileSync(path.join(work, 'api-launch.json'), 'utf8');
  assert.equal(config.includes('zk-test'), false);
  assert.equal(config.includes('or-test'), false);
  assert.equal(JSON.parse(config).baseUrl, 'https://api.z.ai/api/paas/v4');
  const fingerprint = keyFingerprint('zk-test');
  assert.equal(fingerprint.length, 8);
  assert.equal(JSON.stringify({ keyFingerprint: fingerprint }).includes('zk-test'), false);
  const sandbox = dockerClientEnv(env);
  assert.equal(sandbox.ZAI_API_KEY, undefined);
  assert.equal(sandbox.OPENROUTER_API_KEY, undefined);
  assert.equal(vendorOfOpenRouter('anthropic/claude-opus-5.5'), 'anthropic');
  assert.equal(vendorOfOpenRouter('qwen/qwen3.8-max-0902'), 'alibaba');
});

test('claude-zai maps the Z.ai key and leaves cli:claude unchanged', () => {
  const bin = fs.mkdtempSync(path.join(os.tmpdir(), 'claude-bin-'));
  fs.writeFileSync(path.join(bin, 'claude'), '#!/bin/sh\nexit 0\n', { mode: 0o755 });
  const env = { HOME: '/home/inert', PATH: bin, ZAI_API_KEY: 'zk-test', OPENROUTER_API_KEY: 'or-test' };
  const work = fs.mkdtempSync(path.join(os.tmpdir(), 'claude-zai-'));
  const ctx = { bridgeArgs: [], env, runtimeAdapter: () => '/tmp/adapter.js' };
  const zai = families.launch(parseReviewerSpec('cli:claude-zai:glm-5.3'), { ...ctx, workDir: work });
  assert.equal(zai.invocation.env.ANTHROPIC_BASE_URL, 'https://api.z.ai/api/anthropic');
  assert.equal(zai.invocation.env.ANTHROPIC_AUTH_TOKEN, 'zk-test');
  assert.equal(zai.invocation.env.ANTHROPIC_DEFAULT_OPUS_MODEL, 'glm-5.3');
  assert.equal(zai.invocation.env.ANTHROPIC_DEFAULT_SONNET_MODEL, 'glm-5.3');
  assert.equal(zai.invocation.env.ANTHROPIC_DEFAULT_HAIKU_MODEL, 'glm-5.3-flash');
  assert.equal(zai.invocation.env.API_TIMEOUT_MS, '3000000');
  assert.equal(zai.invocation.env.ZAI_API_KEY, undefined);
  assert.equal(zai.sessionMeta.claudeCode.options.settings, undefined, 'a Claude that does not advertise auth status --settings gets no settings object');
  const plain = families.launch(parseReviewerSpec('cli:claude:opus'), { ...ctx, workDir: fs.mkdtempSync(path.join(os.tmpdir(), 'claude-plain-')) });
  assert.equal(plain.sessionMeta.claudeCode.options.settings, undefined);
  const flaggedBin = fs.mkdtempSync(path.join(os.tmpdir(), 'claude-flag-bin-'));
  fs.writeFileSync(path.join(flaggedBin, 'claude'), '#!/bin/sh\nif [ "$1" = auth ]; then echo "--settings"; fi\nexit 0\n', { mode: 0o755 });
  const flagged = families.launch(parseReviewerSpec('cli:claude:opus'), { ...ctx, env: { ...env, PATH: flaggedBin }, workDir: fs.mkdtempSync(path.join(os.tmpdir(), 'claude-flagged-')) });
  assert.equal(flagged.sessionMeta.claudeCode.options.settings.forceLoginMethod, 'claudeai');
  assert.equal(plain.invocation.env.ANTHROPIC_AUTH_TOKEN, undefined);
  assert.equal(plain.invocation.env.ANTHROPIC_BASE_URL, undefined);
});
