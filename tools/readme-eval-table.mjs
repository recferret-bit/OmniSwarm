#!/usr/bin/env node
// Copies the golden-eval totals and the default-rounds decision from engine/eval/RESULTS.md into the
// README between the eval-table markers, so the README never carries hand-copied numbers.
//   node tools/readme-eval-table.mjs           rewrite README.md in place
//   node tools/readme-eval-table.mjs --check   exit 1 if README.md is stale
// The date and commit line of RESULTS.md is left out on purpose: `npm run eval:golden` rewrites it on every run.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const README = path.join(ROOT, 'README.md');
export const RESULTS = path.join(ROOT, 'engine/eval/RESULTS.md');
export const START = '<!-- eval-table:start (generated by tools/readme-eval-table.mjs from engine/eval/RESULTS.md; do not edit) -->';
export const END = '<!-- eval-table:end -->';

/** The README block for one RESULTS.md text: the decision line and the totals rows under the table header. */
export function evalBlock(results) {
  const lines = results.split('\n');
  const decision = lines.find((line) => line.startsWith('Default debate rounds:'));
  const header = lines.findIndex((line) => line.startsWith('| repo | mode |'));
  if (!decision || header < 0) throw new Error('RESULTS.md has no "Default debate rounds:" line or no results table');
  const totals = lines.slice(header + 2).filter((line) => line.startsWith('| **total** |'));
  if (!totals.length) throw new Error('RESULTS.md table has no **total** rows');
  const table = ['| mode | recall | precision | decoy FP | dedup | conformity | cost USD |', '|---|---:|---:|---:|---:|---:|---:|'];
  for (const row of totals) table.push(`|${row.split('|').slice(2).join('|')}`);
  return [decision, '', ...table].join('\n');
}

/** README text with the block between the markers replaced. */
export function inject(readme, block) {
  const start = readme.indexOf(START);
  const end = readme.indexOf(END);
  if (start < 0 || end < start) throw new Error('README.md has no eval-table markers');
  return `${readme.slice(0, start + START.length)}\n${block}\n${readme.slice(end)}`;
}

function main(argv) {
  const readme = fs.readFileSync(README, 'utf8');
  const next = inject(readme, evalBlock(fs.readFileSync(RESULTS, 'utf8')));
  if (argv.includes('--check')) {
    if (next !== readme) {
      console.error('README.md eval table is stale: run node tools/readme-eval-table.mjs');
      return 1;
    }
    console.log('README eval table matches engine/eval/RESULTS.md');
    return 0;
  }
  if (next !== readme) fs.writeFileSync(README, next);
  console.log(next === readme ? 'README eval table already current' : 'README eval table updated');
  return 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) process.exitCode = main(process.argv.slice(2));
