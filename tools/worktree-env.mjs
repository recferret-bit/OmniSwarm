#!/usr/bin/env node
// Per-worktree isolation (PRODUCT_WAVES section 7): derives ports, a database name and a
// reports directory from the branch name and writes .env.worktree. Same branch, same file.
//   node tools/worktree-env.mjs --branch wave/w03-api-reviewers [--out <file>] [--pg <url-base>]
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

export function slugify(branch, sep) {
  const slug = branch.toLowerCase().replace(/[^a-z0-9]+/g, sep).replace(new RegExp(`^${sep}+|${sep}+$`, 'g'), '');
  if (!slug) throw new Error(`branch name has no usable characters: ${JSON.stringify(branch)}`);
  return slug;
}

export function portBase(branch) {
  const n = crypto.createHash('sha256').update(branch).digest().readUInt32BE(0);
  return 4100 + (n % 9) * 100; // 4100..4900 step 100
}

export function worktreeEnv(branch, { pg = 'postgres://localhost:5432' } = {}) {
  const base = portBase(branch);
  let db = `omniswarm_${slugify(branch, '_')}`;
  if (db.length > 63) db = `${db.slice(0, 54)}_${crypto.createHash('sha256').update(branch).digest('hex').slice(0, 8)}`; // Postgres identifier limit
  return {
    OMNI_BRANCH: branch,
    OMNI_PORT_BASE: String(base),
    OMNI_API_PORT: String(base + 1),
    OMNI_LANDING_PORT: String(base + 173),
    DATABASE_URL: `${pg.replace(/\/+$/, '')}/${db}`,
    OMNI_REPORTS_DIR: `reports/wt-${slugify(branch, '-')}`,
  };
}

export function render(env) {
  return `# Generated by tools/worktree-env.mjs. Not committed. Contains no secrets.\n${Object.entries(env).map(([k, v]) => `${k}=${v}`).join('\n')}\n`;
}

function main(argv) {
  const opt = {};
  for (let i = 0; i < argv.length; i += 2) {
    if (!['--branch', '--out', '--pg'].includes(argv[i]) || argv[i + 1] === undefined) throw new Error(`usage: worktree-env.mjs --branch <name> [--out <file>] [--pg <postgres url base>]`);
    opt[argv[i].slice(2)] = argv[i + 1];
  }
  if (!opt.branch) throw new Error('usage: worktree-env.mjs --branch <name> [--out <file>] [--pg <postgres url base>]');
  const env = worktreeEnv(opt.branch, { pg: opt.pg || process.env.OMNI_PG_URL || undefined });
  const out = path.resolve(opt.out || path.join(ROOT, '.env.worktree'));
  fs.writeFileSync(out, render(env));
  process.stdout.write(`wrote ${path.relative(process.cwd(), out) || out}\n${render(env)}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try { main(process.argv.slice(2)); } catch (e) { process.stderr.write(`${e.message}\n`); process.exit(2); }
}
