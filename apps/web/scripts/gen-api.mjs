// Generates src/lib/api/schema.gen.ts from packages/schemas/intake-api.schema.json.
// The schema is a bag of $defs, so a synthetic root lists every def as a property;
// json-schema-to-typescript then emits one named type per def (QuoteResponse,
// ErrorCode, ...). `--check` regenerates in memory and fails when the committed
// file is stale, so a DTO change in the schema breaks `npm test` and tsc together.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile } from 'json-schema-to-typescript';

const here = path.dirname(fileURLToPath(import.meta.url));
const schemasDir = path.resolve(here, '../../../packages/schemas');
const target = path.resolve(here, '../src/lib/api/schema.gen.ts');

function loadSchema(name) {
  return JSON.parse(fs.readFileSync(path.join(schemasDir, name), 'utf8'));
}

function pascal(name) {
  return name.replace(/(^|-)([a-z0-9])/g, (_, _dash, char) => char.toUpperCase());
}

function titled(defs) {
  return Object.fromEntries(Object.entries(defs).map(([name, def]) => [name, { ...def, title: pascal(name) }]));
}

export async function generate() {
  const api = loadSchema('intake-api.schema.json');
  const attestation = loadSchema('attestation.schema.json');
  const defs = titled(api.$defs);
  defs.attestation = { ...attestation, $schema: undefined, $id: undefined, title: 'Attestation' };
  const rewrite = (value) => JSON.parse(JSON.stringify(value).replaceAll('"attestation.schema.json"', '"#/$defs/attestation"'));
  const root = {
    title: 'IntakeApi',
    type: 'object',
    additionalProperties: false,
    properties: Object.fromEntries(Object.keys(defs).map((name) => [name, { $ref: `#/$defs/${name}` }])),
    $defs: rewrite(defs),
  };
  const body = await compile(root, 'IntakeApi', {
    bannerComment: '/* Generated by scripts/gen-api.mjs from packages/schemas/intake-api.schema.json. Do not edit. */',
    additionalProperties: false,
    unreachableDefinitions: false,
    style: { singleQuote: true, printWidth: 120 },
  });
  return body;
}

const output = await generate();
if (process.argv.includes('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (current !== output) {
    console.error('src/lib/api/schema.gen.ts is stale: run `npm run gen:api -w apps/web`');
    process.exit(1);
  }
  console.log('schema.gen.ts matches intake-api.schema.json');
} else {
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, output);
  console.log(`wrote ${path.relative(process.cwd(), target)}`);
}
